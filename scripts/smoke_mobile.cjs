// Run only with synthetic accounts in a disposable database (same guard as smoke_browser.cjs).
'use strict';
const {chromium} = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
if (process.env.DAVIGURUMI_SMOKE_ISOLATED !== '1') throw Error('A disposable database is required.');
const base = process.env.DAVIGURUMI_SMOKE_URL || 'http://127.0.0.1:8110';
const out = process.env.DAVIGURUMI_MOBILE_OUTPUT || '/tmp/davigurumi-mobile-review';
fs.mkdirSync(out, {recursive: true});
(async () => {
  const browser = await chromium.launch({executablePath: process.env.CHROMIUM_PATH || '/usr/bin/chromium', headless: true, args: ['--no-sandbox']});
  const context = await browser.newContext({viewport: {width: 390, height: 844}, isMobile: true, hasTouch: true});
  const page = await context.newPage(); page.setDefaultTimeout(15000);
  const errors = [], axeResults = [];
  page.on('pageerror', e => errors.push(e.message));
  page.on('response', r => {if (r.status() >= 500) errors.push(`HTTP ${r.status()} ${new URL(r.url()).pathname}`);});
  const axe = process.env.DAVIGURUMI_AXE_PATH ? fs.readFileSync(process.env.DAVIGURUMI_AXE_PATH, 'utf8') : null;
  const checkAxe = async (label, target = page) => {
    if (!axe) return;
    await target.evaluate(axe);
    const result = await target.evaluate(async () => (await axe.run(document, {runOnly: {type: 'tag', values: ['wcag2a', 'wcag2aa', 'wcag21aa', 'wcag22aa']}})).violations.map(v => ({id: v.id, impact: v.impact, targets: v.nodes.map(n => n.target)})));
    axeResults.push({label, violations: result});
    assert.deepEqual(result, [], label);
  };
  const go = async route => {assert.equal((await page.goto(base + route)).status(), 200, route);};
  const noOverflow = async label => assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, label);
  try {
    const username = 'mobile_' + Date.now();
    await go('/conta/criar/');
    await page.locator('#id_first_name').fill('Marina');
    await page.locator('#id_username').fill(username);
    await page.locator('#id_email').fill(username + '@example.test');
    await page.locator('#id_password1').fill('Mobile-Synthetic-Only-2026!');
    await page.locator('#id_password2').fill('Mobile-Synthetic-Only-2026!');
    await page.getByRole('button', {name: 'Começar', exact: true}).click();
    await page.waitForURL(base + '/');
    await go('/materiais/novo/');
    assert.equal(await page.locator('#mobile-menu').isVisible(), false);
    assert.equal(await page.locator('.sidebar').isVisible(), false);
    assert.equal(await page.locator('.bottom-navigation > *').count(), 5);
    assert((await page.locator('h1').boundingBox()).y < 200, 'Content starts directly below header');
    for (const input of await page.locator('main input:not([type=hidden]):not([type=checkbox]):not([type=radio]), main select').all()) {
      assert(Number(await input.evaluate(e => parseFloat(getComputedStyle(e).fontSize))) >= 16, 'No input zoom caused by small text');
    }
    await page.locator('#id_name').fill('Fio de algodão para o próximo amigurumi');
    const topTrigger = page.locator('.mobile-header [data-menu-open]');
    await topTrigger.click();
    await page.locator('#mobile-menu').waitFor({state: 'visible'});
    assert.equal(await topTrigger.getAttribute('aria-expanded'), 'true');
    assert.equal(await page.locator('#mobile-menu [data-workspace-nav] > *').count(), 5);
    assert.equal(await page.locator('#mobile-menu a.active').innerText(), 'Materiais e estoque');
    await checkAxe('mobile dialog');
    await page.screenshot({path: out + '/menu-celular.png'});
    await page.keyboard.press('Shift+Tab');
    assert(await page.evaluate(() => !!document.activeElement.closest('#mobile-menu')), 'Focus stays in modal');
    await page.keyboard.press('Tab');
    assert(await page.evaluate(() => !!document.activeElement.closest('#mobile-menu')));
    await page.keyboard.press('Escape');
    assert.equal(await page.locator('#mobile-menu').isVisible(), false);
    await page.waitForFunction(() => document.querySelector('.mobile-header [data-menu-open]').getAttribute('aria-expanded') === 'false');
    assert.equal(await topTrigger.getAttribute('aria-expanded'), 'false');
    assert.equal(await topTrigger.evaluate(e => document.activeElement === e), true);
    assert.equal(await page.locator('#id_name').inputValue(), 'Fio de algodão para o próximo amigurumi');
    await topTrigger.click();
    await page.mouse.click(2, 2);
    await page.locator('#mobile-menu').waitFor({state: 'hidden'});
    await topTrigger.click();
    await page.locator('#mobile-menu details').evaluateAll(groups => groups.forEach(group => group.open = true));
    await page.locator('#mobile-menu').evaluate(menu => menu.scrollTop = menu.scrollHeight);
    const footer = await page.locator('#mobile-menu .logout').boundingBox();
    assert(footer && footer.y >= 0 && footer.y + footer.height <= 844, 'Long menu scrolls to account controls');
    await page.locator('[data-menu-close]').click();
    await page.locator('h1').click();
    await page.screenshot({path: out + '/novo-material-celular.png'});
    await page.locator('#id_kind').selectOption('yarn');
    await page.locator('#id_unit').selectOption('g');
    await page.locator('#id_initial_quantity').fill('250');
    await page.locator('#id_initial_unit_cost').fill('0.20');
    await page.getByRole('button', {name: 'Cadastrar material', exact: true}).click();
    await page.waitForURL(/\/materiais\/[a-f0-9-]+\/$/);
    await go('/materiais/');
    assert.equal(await page.locator('table.mobile-cards').count(), 1);
    assert((await page.locator('table tbody').innerText()).includes('250'));
    await checkAxe('mobile list cards');
    await page.screenshot({path: out + '/materiais-celular.png'});
    const routes = ['/', '/materiais/', '/materiais/novo/', '/orcamentos/', '/orcamentos/novo/', '/pedidos/', '/compras/', '/projetos/', '/precificacao/', '/dados/', '/notificacoes/relatorios/', '/conta/seguranca/'];
    const widths = [320, 360, 390, 430, 600, 768, 1024, 1440];
    for (const width of widths) {
      await page.setViewportSize({width, height: 900});
      for (const route of routes) {await go(route); await noOverflow(`${width}px ${route}`);}
    }
    await go('/materiais/');
    assert.equal(await page.locator('.sidebar').isVisible(), true);
    assert.equal(await page.locator('.bottom-navigation').isVisible(), false);
    await page.screenshot({path: out + '/materiais-computador.png', fullPage: true});
    await checkAxe('desktop grouped navigation');
    await page.setViewportSize({width: 390, height: 844});
    await page.locator('.bottom-navigation [data-menu-open]').click();
    await page.locator('#mobile-menu summary').filter({hasText: 'Vendas e produção'}).click();
    await page.locator('#mobile-menu').getByRole('link', {name: 'Biblioteca de peças', exact: true}).click();
    await page.waitForURL(base + '/projetos/');
    assert.equal(await page.locator('h1').innerText(), 'Biblioteca de peças');
    await page.locator('.mobile-header [data-menu-open]').click();
    await page.setViewportSize({width: 1440, height: 900});
    await page.locator('#mobile-menu').waitFor({state: 'hidden'});
    await page.waitForFunction(() => !document.body.classList.contains('menu-open'));
    assert.equal(await page.locator('#mobile-menu').isVisible(), false, 'Resizing closes modal');
    assert.equal(await page.locator('body').evaluate(e => e.classList.contains('menu-open')), false);
    await page.setViewportSize({width: 844, height: 390});
    await page.locator('.mobile-header [data-menu-open]').click();
    assert((await page.locator('#mobile-menu').boundingBox()).height <= 390, 'Landscape menu fits viewport');
    await page.locator('[data-menu-close]').click();
    await page.setViewportSize({width: 320, height: 700});
    await go('/materiais/novo/');
    await page.evaluate(() => document.documentElement.style.fontSize = '200%');
    await noOverflow('200% text at 320px');
    await page.screenshot({path: out + '/texto-ampliado.png', fullPage: true});
    await page.evaluate(() => document.documentElement.style.fontSize = '');
    await page.emulateMedia({reducedMotion: 'reduce'});
    await page.locator('.mobile-header [data-menu-open]').click();
    assert.equal(await page.locator('#mobile-menu').evaluate(e => getComputedStyle(e).animationName), 'none');
    await page.keyboard.press('Escape');
    const auth = await context.storageState();
    const noJs = await browser.newContext({viewport: {width: 390, height: 844}, javaScriptEnabled: false, storageState: auth});
    const fallback = await noJs.newPage(); await fallback.goto(base + '/materiais/novo/');
    await fallback.locator('.fallback-navigation > summary').click();
    assert.equal(await fallback.locator('.fallback-navigation').getByRole('link', {name: 'Materiais e estoque', exact: true}).isVisible(), true);
    await noJs.close();
    const anonymous = await browser.newContext({viewport: {width: 390, height: 844}});
    const login = await anonymous.newPage();
    assert.equal((await login.goto(base + '/conta/entrar/')).status(), 200);
    assert((await login.locator('.auth-card').boundingBox()).y < 160, 'Login form appears before introduction on phones');
    assert((await login.locator('#id_username').boundingBox()).y < 400);
    await checkAxe('mobile login', login);
    await anonymous.close();
    assert.deepEqual(errors, []);
    fs.writeFileSync(out + '/result.json', JSON.stringify({widths, routes: routes.length, layoutChecks: widths.length * routes.length, nativeDialog: true, focusAndEscape: true, unsavedFormPreserved: true, tableCards: true, enlargedText: '200% at 320px', landscape: true, reducedMotion: true, noJavascriptFallback: true, errors, accessibility: axeResults}, null, 2));
    console.log(JSON.stringify({layoutChecks: widths.length * routes.length, errors, accessibilityChecks: axeResults.length, screenshots: out}));
  } finally {await browser.close();}
})().catch(e => {console.error(e); process.exitCode = 1;});
